function inferCategory(number: number): ElementCategory {
  if (number >= 57 && number <= 71) return "lanthanide";
  if (number >= 89 && number <= 103) return "actinide";
  if ([2, 10, 18, 36, 54, 86, 118].includes(number)) return "noble";
  if ([9, 17, 35, 53, 85, 117].includes(number)) return "halogen";
  if ([3, 11, 19, 37, 55, 87].includes(number)) return "alkali";
  if ([4, 12, 20, 38, 56, 88].includes(number)) return "alkaline";
  if ((number >= 21 && number <= 30) || (number >= 39 && number <= 48) || (number >= 72 && number <= 80) || (number >= 104 && number <= 112)) return "transition";
  return "post-transition";
}

function inferPeriod(number: number) {
  if (number <= 2) return 1;
  if (number <= 10) return 2;
  if (number <= 18) return 3;
  if (number <= 36) return 4;
  if (number <= 54) return 5;
  if (number <= 86) return 6;
  return 7;
}

